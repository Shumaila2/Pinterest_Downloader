COOKIE_FILE = cookie_file_path()

# ---------------------------------------------------------------
# Cookie helpers
# ---------------------------------------------------------------
def _load_flat_cookies():
    """Read cookies.json fresh every time (so newly saved cookies are used)."""
    with open(COOKIE_FILE, "r") as f:
        return json.load(f)


def _write_netscape_cookies(cookies: dict, cookie_path: Path):
    """Write cookies in Netscape format so yt-dlp can use them."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# This file was generated by pinterest_dl.py",
        ""
    ]
    expiry = str(int(time.time()) + 3600 * 24 * 365 * 5)
    domain = ".pinterest.com"
    path = "/"
    secure = "TRUE"
    flag = "TRUE"

    for name, value in cookies.items():
        if not value:
            continue
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expiry}\t{name}\t{value}")

    cookie_path.write_text("\n".join(lines), encoding="utf-8")


def _load_cookies_for_pinterest_dl():
    """pinterest-dl wants Selenium-style cookie dicts instead of a flat dict."""
    flat_cookies = _load_flat_cookies()
    far_future = int(time.time()) + 3600 * 24 * 365

    return [
        {
            "name": name,
            "value": value,
            "domain": ".pinterest.com",
            "path": "/",
            "secure": True,
            "httpOnly": True,
            "sameSite": "Lax",
            "expiry": far_future,
        }
        for name, value in flat_cookies.items()
    ]


def _ensure_ffmpeg_on_path():
    """Let pinterest-dl find the ffmpeg.exe that sits next to this script."""
    from paths import resource_path
    script_dir = resource_path("pin_video_down")
    if script_dir not in os.environ.get("PATH", ""):
        os.environ["PATH"] = script_dir + os.pathsep + os.environ.get("PATH", "")


# ---------------------------------------------------------------
# Method 1: yt-dlp (first attempt - gives video WITH audio)
# ---------------------------------------------------------------
def _download_with_ytdlp(url, download_path, output_template, progress_callback):
    """Returns True on success, False on any failure."""
    try:
        import yt_dlp
    except ImportError:
        print("DEBUG: yt-dlp is not installed, skipping to fallback")
        return False

    try:
        cookies = _load_flat_cookies()

        with tempfile.TemporaryDirectory() as tmpdir:
            cookie_file = Path(tmpdir) / "cookies.txt"
            _write_netscape_cookies(cookies, cookie_file)

            from paths import resource_path
            script_dir = Path(resource_path("pin_video_down"))
            ffmpeg_local = script_dir / ("ffmpeg.exe" if os.name == "nt" else "ffmpeg")
            ffmpeg_location = str(ffmpeg_local) if ffmpeg_local.exists() else None

            if download_path:
                Path(download_path).mkdir(parents=True, exist_ok=True)
                output_template = str(Path(download_path) / output_template)

            def progress_hook(d):
                if d['status'] == 'downloading':
                    p = d.get('_percent_str', '').strip()
                    p_clean = re.sub(r'\x1b\[[0-9;]*[a-zA-Z]', '', p)
                    p_clean = re.sub(r'\[\d+;\d+m|\[\d+m', '', p_clean)
                    if progress_callback:
                        progress_callback(p_clean)

            ydl_opts = {
                "cookiefile": str(cookie_file),
                "outtmpl": output_template,
                "noplaylist": True,
                "quiet": False,
                "merge_output_format": "mp4",
                "format": "bv*+ba/b",
                "progress_hooks": [progress_hook],
                **({"ffmpeg_location": ffmpeg_location} if ffmpeg_location else {})
            }

            with yt_dlp.YoutubeDL(ydl_opts) as ydl:
                ydl.extract_info(url, download=True)
            return True

    except Exception as e:
        print("DEBUG: yt-dlp failed, will try pinterest-dl fallback:", e)
        return False


# ---------------------------------------------------------------
# Method 2: pinterest-dl (fallback - can reach private pins,
# but the video may come out without sound)
# ---------------------------------------------------------------
def _download_with_pinterest_dl(url, download_path, progress_callback):
    """Returns True on success, False on any failure."""
    try:
        _ensure_ffmpeg_on_path()
        cookies = _load_cookies_for_pinterest_dl()

        if download_path:
            Path(download_path).mkdir(parents=True, exist_ok=True)

        if progress_callback:
            progress_callback("0.0%")

        downloaded = (
            PinterestDL.with_api()
            .with_cookies(cookies)
            .scrape_and_download(
                url=url,
                output_dir=download_path or os.getcwd(),
                num=1,
                download_streams=True,
            )
        )

        if not downloaded:
            return False

        if progress_callback:
            progress_callback("100.0%")
        return True

    except Exception as e:
        print("DEBUG: pinterest-dl fallback failed:", e)
        return False


# ---------------------------------------------------------------
# Main entry point (same name + arguments as before, so the rest
# of the app doesn't need any changes)
# ---------------------------------------------------------------
def download_pin(url: str, download_path: str = None, output_template: str = "%(id)s.%(ext)s", progress_callback=None):
    # Attempt 1: yt-dlp (best quality, has audio)
    if _download_with_ytdlp(url, download_path, output_template, progress_callback):
        return "✔ Download complete!"

    # Attempt 2: pinterest-dl (works for more pins, audio may be missing)
    print("DEBUG: falling back to pinterest-dl...")
    if _download_with_pinterest_dl(url, download_path, progress_callback):
        return "✔ Download complete!"

    return "❌ Couldn't access this pin. It may be private or from a private board."
            
                
class pin_down():
    
    def __init__(self):
        self.window = None
        
    def ping(self):
        return "ready"

    def reset_cookies(self):
        """Delete saved cookies so the setup window shows on next launch."""
        try:
            if os.path.exists(COOKIE_FILE):
                os.remove(COOKIE_FILE)
            return True
        except Exception as e:
            print("DEBUG: could not delete cookies:", e)
            return False
        
    def select_folder(self):
        folder = webview.windows[0].create_file_dialog(webview.FileDialog.FOLDER)
        return folder
    
    def download(self, url, folder):
    
        if not url or not folder:
            return "✖ Please enter a link and select a folder first!"
        
        def run_download():
            def send_progress(percent):
                self.window.evaluate_js(f"updateProgress('{percent}')")
                    
            try:
                result = download_pin(url, download_path=folder, progress_callback=send_progress)
                final_msg =  result or "❌ Something went wrong..Please try again"
                
            except Exception:
                return "❌ Something went wrong..Please try again"
            
            self.window.evaluate_js(f"downloadFinished({json.dumps(final_msg)})")
        
        threading.Thread(target=run_download, daemon=True).start()


def after_loaded():
    """Called automatically once the window is fully loaded."""
    win = webview.windows[0]

    # Wait a bit longer to make sure internal pywebview loop is finished
    # (this hides your loading text only after everything is ready)
    for i in range(6):  # roughly 6 seconds total
        time.sleep(1)
        print(f"[Loader] Still initializing... {i+1}s")

    # now the JS side will hide the loading message
    win.evaluate_js("backendReady()")
    print("[Loader] Backend is ready!")



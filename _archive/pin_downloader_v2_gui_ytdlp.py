def _write_netscape_cookies(cookies: dict, cookie_path: Path):
    """
    Write cookies in Netscape format so yt-dlp can use them.
    """
    lines = [
        "# Netscape HTTP Cookie File",
        "# This file was generated by pinterest_dl.py",
        ""
    ]
    # Use a far future expiry
    expiry = str(int(time.time()) + 3600 * 24 * 365 * 5)

    # We write to .pinterest.com for widest match
    domain = ".pinterest.com"
    path = "/"
    secure = "TRUE"   # Pinterest uses HTTPS
    flag = "TRUE"

    for name, value in cookies.items():
        if not value:
            continue
        # Netscape format: domain <tab> flag <tab> path <tab> secure <tab> expires <tab> name <tab> value
        lines.append(f"{domain}\t{flag}\t{path}\t{secure}\t{expiry}\t{name}\t{value}")

    cookie_path.write_text("\n".join(lines), encoding="utf-8")


def download_pin(url: str, download_path: str = None, output_template: str = "%(id)s.%(ext)s", progress_callback = None):
    """
    Download a single Pinterest pin (video) with audio merged to MP4.
    Args:
        url (str): Pinterest pin URL
        download_path (str): Folder path where the file should be saved
        output_template (str): Filename template (default: title.ext)
    """
    try:
        import yt_dlp
    except ImportError:
        print("Error: yt-dlp is not installed. Run: pip install yt-dlp")
        return

    # Create a temp cookies.txt in Netscape format
    with tempfile.TemporaryDirectory() as tmpdir:
        cookie_file = Path(tmpdir) / "cookies.txt"
        _write_netscape_cookies(COOKIES, cookie_file)

        # If ffmpeg.exe is in the same folder as this script, let yt-dlp know
        script_dir = Path(__file__).resolve().parent
        ffmpeg_local = script_dir / ("ffmpeg.exe" if os.name == "nt" else "ffmpeg")
        ffmpeg_location = str(ffmpeg_local) if ffmpeg_local.exists() else None

        # ✅ Build output path
        if download_path:
            Path(download_path).mkdir(parents=True, exist_ok=True)
            output_template = str(Path(download_path) / output_template)
        
        def progress_hook(d):
            if d['status'] == 'downloading':
                p = d.get('_percent_str', '').strip()
                # Remove ANSI color codes like [0;94m etc.
                p_clean = re.sub(r'\x1b\[[0-9;]*[a-zA-Z]', '', p)
                p_clean = re.sub(r'\[\d+;\d+m|\[\d+m', '', p_clean)
                
                if progress_callback:
                    progress_callback(p_clean)
                    
        ydl_opts = {
            "cookiefile": str(cookie_file),
            "outtmpl": output_template,                    # output filename template
            "noplaylist": True,                            # just the single pin
            "quiet": False,                                # show progress
            "merge_output_format": "mp4",                  # final file type
            "format": "bv*+ba/b",                          # best video+best audio, else best
            "progress_hooks": [progress_hook],
            **({"ffmpeg_location": ffmpeg_location} if ffmpeg_location else {})
        }
        

        # Try to download
        with yt_dlp.YoutubeDL(ydl_opts) as ydl:
            try:
                ydl.extract_info(url, download=True)
                return "✔ Download complete!"
            except yt_dlp.utils.DownloadError as e:
                if "already downloaded" in str(e).lower():
                    return "Download complete!"
                return "❌ Something went wrong..Please try again"
            except Exception:
                return "❌ Something went wrong..Please try again"
            
                
class pin_down():
    
    def __init__(self):
        self.window = None
        
    def ping(self):
        return "ready"
        
    def select_folder(self):
        folder = webview.windows[0].create_file_dialog(webview.FileDialog.FOLDER)
        return folder
    
    def download(self, url, folder):
    
        if not url or not folder:
            return "✖ Please enter a link and select a folder first!"
        
        def run_download():
            def send_progress(percent):
                self.window.evaluate_js(f"updateProgress('{percent}')")
                    
            try:
                result = download_pin(url, download_path=folder, progress_callback=send_progress)
                final_msg =  result or "❌ Something went wrong..Please try again"
                
            except Exception:
                return "❌ Something went wrong..Please try again"
            
            self.window.evaluate_js(f"downloadFinished({json.dumps(final_msg)})")
        
        threading.Thread(target=run_download, daemon=True).start()


def after_loaded():
    """Called automatically once the window is fully loaded."""
    win = webview.windows[0]

    # Wait a bit longer to make sure internal pywebview loop is finished
    # (this hides your loading text only after everything is ready)
    for i in range(6):  # roughly 6 seconds total
        time.sleep(1)
        print(f"[Loader] Still initializing... {i+1}s")

    # now the JS side will hide the loading message
    win.evaluate_js("backendReady()")
    print("[Loader] Backend is ready!")


